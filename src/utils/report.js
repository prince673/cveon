// Shareable report builders: Markdown / JSON summaries of a lookup result.
// Pure string building — the caller decides whether to copy or share it.

import { formatDate } from './formatters'

function percent(x) {
  return typeof x === 'number' ? `${(x * 100).toFixed(2)}%` : 'N/A'
}

/**
 * Human-readable Markdown summary of a CVE lookup result.
 */
export function buildMarkdownSummary(cve) {
  if (!cve?.cve_id) return ''
  const best = cve.best_cvss
  const kev = cve.kev
  const epss = cve.epss
  const risk = cve.risk

  const lines = []
  lines.push(`# ${cve.cve_id}`)
  if (best) {
    lines.push('')
    lines.push(`**CVSS ${best.version}:** ${best.score}/10 (${best.severity})`)
    if (best.vector_string) lines.push(`**Vector:** \`${best.vector_string}\``)
  }
  if (epss?.score != null) {
    lines.push(`**EPSS:** ${percent(epss.score)}` +
      (epss.percentile != null ? ` (P${Math.round(epss.percentile * 100)} percentile)` : ''))
  }
  if (kev) {
    lines.push(`**CISA KEV:** Listed — known exploited` +
      (kev.due_date ? `, patch due ${formatDate(kev.due_date)}` : '') +
      (kev.known_ransomware_campaign_use ? ' — used in ransomware campaigns' : ''))
  } else {
    lines.push('**CISA KEV:** Not listed')
  }
  if (risk) {
    lines.push(`**Risk priority:** ${risk.priority} — ${risk.level} (${risk.score}/100)`)
  }

  lines.push('')
  lines.push('## Description')
  lines.push(cve.description || 'No description available.')

  if (cve.cwes?.length) {
    lines.push('')
    lines.push('## Weaknesses')
    lines.push(cve.cwes.map(c => `- ${c}`).join('\n'))
  }
  if (cve.products?.length) {
    lines.push('')
    lines.push('## Affected products')
    lines.push(cve.products.slice(0, 20).map(p => `- ${p}`).join('\n'))
  }
  if (cve.references?.length) {
    lines.push('')
    lines.push('## References')
    lines.push(cve.references.slice(0, 10).map(r => `- ${r}`).join('\n'))
  }
  if (cve.exploits?.length) {
    lines.push('')
    lines.push('## Public exploits')
    lines.push(cve.exploits.map(e => `- [${e.name || e.url}](${e.url})`).join('\n'))
  }

  lines.push('')
  lines.push('---')
  lines.push(`*Generated by CVEon on ${new Date().toISOString().slice(0, 10)} — for authorized security research.*`)
  return lines.join('\n')
}

/**
 * Stable JSON summary (drops nothing — the data is already RAM-only).
 */
export function buildJsonSummary(cve) {
  if (!cve) return ''
  return JSON.stringify(cve, null, 2)
}
